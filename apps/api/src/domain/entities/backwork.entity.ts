export type Semester = 'Spring' | 'Summer' | 'Fall' | 'Winter';

export type AssignmentType =
  | 'Exam'
  | 'Midterm'
  | 'Final Exam'
  | 'Quiz'
  | 'Homework'
  | 'Lab'
  | 'Project'
  | 'Study Guide'
  | 'Notes'
  | 'Other';

export type DocumentVariant = 'Student Copy' | 'Blank Copy' | 'Answer Key';

export interface BackworkDepartment {
  id: string;
  chapter_id: string;
  code: string;
  name: string | null;
  created_at: string;
}

/**
 * What a chapter calls one course: a display name and the nicknames members
 * type for it. Keyed by department and `course_key` (the course number trimmed
 * and lowercased, generated by the database); files join it by those two.
 */
export interface BackworkCourse {
  id: string;
  chapter_id: string;
  department_id: string;
  course_number: string;
  /** Generated: `lower(btrim(course_number))`. Never written. */
  course_key: string;
  name: string | null;
  nicknames: string[];
  created_at: string;
  updated_at: string;
}

export interface BackworkProfessor {
  id: string;
  chapter_id: string;
  name: string;
  created_at: string;
}

/**
 * A draft's unpublished metadata (#5208), in the confirm body's shape. Names,
 * not ids: a department or professor is created only when the draft is
 * published, so a half-typed name never shows up in another member's filters.
 */
export interface BackworkDraftFields {
  title?: string | null;
  department_code?: string | null;
  course_number?: string | null;
  course_name?: string | null;
  professor_name?: string | null;
  year?: number | null;
  semester?: Semester | null;
  assignment_type?: AssignmentType | null;
  assignment_number?: number | null;
  document_variant?: DocumentVariant | null;
  tags?: string[] | null;
  /**
   * The fields the upload-time AI fill set (#5233) and nobody has edited
   * since, so the review table can mark them for checking.
   */
  ai_filled?: string[];
  /** How the last AI fill ended, when one ran. */
  ai_fill?: BackworkAiFillOutcome;
}

/**
 * - `filled`: at least one field was set.
 * - `nothing_found`: the file was read and nothing new could be told.
 * - `unreadable`: the file has too little text to read, likely a scan.
 */
export type BackworkAiFillOutcome = 'filled' | 'nothing_found' | 'unreadable';

export interface BackworkResource {
  id: string;
  chapter_id: string;
  department_id: string | null;
  course_number: string | null;
  professor_id: string | null;
  uploader_id: string;
  title: string | null;
  year: number | null;
  semester: Semester | null;
  assignment_type: AssignmentType | null;
  assignment_number: number | null;
  document_variant: DocumentVariant | null;
  storage_path: string;
  file_hash: string;
  is_redacted: boolean;
  tags: string[];
  created_at: string;
  /**
   * Not null while the row is a draft (#5208): visible only to its uploader,
   * left out of every chapter-wide read. Null once published.
   */
  draft_fields: BackworkDraftFields | null;
}
