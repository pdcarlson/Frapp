#!/usr/bin/env node

// Emits idempotent SQL that loads supabase/seed/chapter_directory.csv into
// public.chapter_directory. Writes SQL to stdout and never talks to a database
// itself — the caller pipes it wherever it belongs.
//
// Why stdout instead of a database client: both bootstrap scripts already share
// one solved answer to "how do I reach the local stack" in
// scripts/lib/local-postgres-acl.sh (host psql against the CLI-reported URL,
// falling back to `docker exec`, with a loopback guard). Opening a second
// connection path here would mean a second thing to get wrong, and this script
// must also run before `npm install` has necessarily happened — so it stays
// dependency-free.
//
//   node scripts/load-chapter-directory.mjs            # SQL to stdout
//
// Context: issue #840. The table shipped empty in every environment because
// nothing ever read the CSV — a repo-wide search for its filename returned
// exactly one hit, the comment in the migration that promised it.

import { loadSeed, SEED_RELATIVE_PATH } from "./lib/chapter-directory-seed.mjs";

/** Single-quote a SQL string literal, or emit NULL. */
function lit(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** Emit a numeric literal, or NULL. Guards against non-finite sneaking in. */
function num(value) {
  if (value === null || value === undefined) return "NULL";
  if (!Number.isFinite(value)) {
    throw new Error(`refusing to emit non-finite number: ${value}`);
  }
  return String(value);
}

function main() {
  const repoRoot = process.cwd();
  const { rows, problems } = loadSeed(repoRoot);

  // The validator (`npm run check:chapter-directory-seed`) is the friendly
  // reporter. This is the backstop: never load a file that failed validation,
  // because a malformed color reaching the database is invisible afterwards —
  // derivePalette turns it into bronze without complaint.
  if (problems.length > 0) {
    console.error(
      `Refusing to emit load SQL — ${SEED_RELATIVE_PATH} has ${problems.length} validation problem(s).`,
    );
    for (const p of problems) {
      console.error(`  ${SEED_RELATIVE_PATH}:${p.line}  [${p.field}]  ${p.message}`);
    }
    console.error("\nRun `npm run check:chapter-directory-seed` for the same report.");
    process.exit(1);
  }

  if (rows.length === 0) {
    console.error(`Refusing to emit load SQL — ${SEED_RELATIVE_PATH} has no rows.`);
    process.exit(1);
  }

  const values = rows
    .map(
      (r) =>
        "  (" +
        [
          lit(r.org_letters),
          lit(r.org_name),
          lit(r.archetype),
          lit(r.chapter_designation),
          lit(r.university),
          lit(r.university_short),
          num(r.founded_year),
          `${lit(JSON.stringify(r.default_colors))}::jsonb`,
          lit(r.website),
          lit(r.source),
        ].join(", ") +
        ")",
    )
    .join(",\n");

  // ── Why this shape, rather than the obvious INSERT ... ON CONFLICT ────────
  //
  // There is no unique constraint to conflict on. `chapter_directory`'s only
  // unique index is its primary key, a random gen_random_uuid() — so ON
  // CONFLICT has no target, and adding one would be a schema migration this
  // issue explicitly does not call for ("the table schema is already correct
  // and needs no migration").
  //
  // Nor can this be a delete-then-insert. `chapters.directory_id` carries
  //   references chapter_directory(id) on delete set null
  // so deleting seed rows would silently null out the directory link of every
  // real chapter that had matched one. Re-running a loader must not quietly
  // detach production data from its directory entry.
  //
  // So: UPDATE the matching rows in place (ids preserved, FK intact), then
  // INSERT only what is genuinely new. Idempotent, and re-running it is a
  // no-op beyond refreshing changed columns.
  const sql = `-- Generated by scripts/load-chapter-directory.mjs — do not edit by hand.
-- Source: ${SEED_RELATIVE_PATH} (${rows.length} rows)
-- Idempotent: safe to re-run. See the script for why this is not ON CONFLICT.

begin;

create temporary table _seed_chapter_directory (
  org_letters          text not null,
  org_name             text not null,
  archetype            text not null,
  chapter_designation  text,
  university           text not null,
  university_short     text not null,
  founded_year         int,
  default_colors       jsonb not null,
  website              text,
  source               text not null
) on commit drop;

insert into _seed_chapter_directory (
  org_letters, org_name, archetype, chapter_designation, university,
  university_short, founded_year, default_colors, website, source
) values
${values};

-- The natural key is (org_letters, university, chapter_designation). The
-- designation is nullable, and SQL's NULL <> NULL would make two undesignated
-- rows for the same org+campus look distinct, so it is coalesced on both sides.
--
-- Updates are scoped to rows this loader owns (source = 'seed'). A row curated
-- by hand or arriving from another source keeps its values; the seed never
-- silently overwrites someone's correction.
update chapter_directory d
set
  org_name            = s.org_name,
  archetype           = s.archetype,
  university_short    = s.university_short,
  founded_year        = s.founded_year,
  default_colors      = s.default_colors,
  website             = s.website
from _seed_chapter_directory s
where d.org_letters = s.org_letters
  and d.university  = s.university
  and coalesce(d.chapter_designation, '') = coalesce(s.chapter_designation, '')
  and d.source = 'seed';

insert into chapter_directory (
  org_letters, org_name, archetype, chapter_designation, university,
  university_short, founded_year, default_colors, website, source
)
select
  s.org_letters, s.org_name, s.archetype, s.chapter_designation, s.university,
  s.university_short, s.founded_year, s.default_colors, s.website, s.source
from _seed_chapter_directory s
where not exists (
  select 1
  from chapter_directory d
  where d.org_letters = s.org_letters
    and d.university  = s.university
    and coalesce(d.chapter_designation, '') = coalesce(s.chapter_designation, '')
);

do $$
declare
  total int;
begin
  select count(*) into total from chapter_directory;
  raise notice 'chapter_directory: % rows after load (% in seed)', total, ${rows.length};
end $$;

commit;
`;

  process.stdout.write(sql);
}

main();
